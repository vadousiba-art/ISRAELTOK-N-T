import fs from "node:fs";
import { BASE, launch, newCtx, settle } from "./lib.mjs";
const OUT = new URL("../capture/explore/", import.meta.url).pathname;
fs.mkdirSync(OUT, { recursive: true });
const browser = await launch();
const ctx = await newCtx(browser);
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("[page error]", e.message));
await page.goto(`${BASE}/join/promo`);
await page.screenshot({ path: OUT + "join.png" });
await page.getByLabel("Display name").fill("Kuro");
await page.getByLabel("Username").fill("kuro_ink");
await page.getByLabel("Email").fill("kuro@example.com");
await page.getByRole("checkbox").check();
await page.getByRole("button", { name: "Join YORU" }).click();
await page.waitForURL(`${BASE}/`);
await settle(page, 1500);
await page.screenshot({ path: OUT + "home.png" });
await page.goto(`${BASE}/u/kuro_ink`);
await settle(page, 1500);
await page.screenshot({ path: OUT + "profile.png" });
await page.getByRole("button", { name: "Edit" }).click();
await settle(page);
await page.screenshot({ path: OUT + "edit.png" });
await page.keyboard.press("Escape");
await page.goto(`${BASE}/settings`);
await settle(page, 1200);
await page.screenshot({ path: OUT + "settings.png" });
await page.screenshot({ path: OUT + "settings-full.png", fullPage: true });
await browser.close();
console.log("ok");
