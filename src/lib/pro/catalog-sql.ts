import { CATALOG, CATALOG_VERSION, STAFF } from "./catalog";
import type { Item } from "./types";

// The catalog rows the database needs (ids, categories, unlock rules, status,
// and the filter parameters for feed presets and hubs). Generated into
// migration 0009 by `npm run pro:catalog`; a test keeps the two identical.
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
export function catalogSql(items: Item[] = CATALOG): string {
  const rows = items.map((i) => {
    const p = i.cat === "feed" || i.cat === "hub" ? JSON.stringify(i.p) : "{}";
    return `  (${q(i.id)}, ${q(i.cat)}, ${q(i.unlock)}, ${q(i.status)}, ${q(p)}::jsonb, ${CATALOG_VERSION})`;
  });
  return [
    "insert into public.pro_catalog (id, cat, unlock, status, p, version) values",
    rows.join(",\n"),
    "on conflict (id) do update set cat = excluded.cat, unlock = excluded.unlock, status = excluded.status, p = excluded.p, version = excluded.version;",
  ].join("\n");
}
export const BEGIN = "-- BEGIN CATALOG (generated by `npm run pro:catalog`; do not edit by hand)";
export const END = "-- END CATALOG";
// Staff items live in migration 0010.
export const staffSql = () => catalogSql(STAFF);
export const STAFF_BEGIN = "-- BEGIN STAFF CATALOG (generated by `npm run pro:catalog`; do not edit by hand)";
export const STAFF_END = "-- END STAFF CATALOG";
