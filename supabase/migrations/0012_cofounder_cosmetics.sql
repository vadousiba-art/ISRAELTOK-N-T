-- YORU — the co-founder's set. docs/pro-universe.md ("Staff cosmetics")
--
-- Co-Founder's Circuit, worn only by Jesse (@Jeskov007), YORU's co-founder.
-- It adds a third kind of staff unlock next to 'staff:owner' and
-- 'staff:admin': 'staff:member:<profile id>', a personal set that only that
-- one account can wear, and only while it is staff (owner or admin). As with
-- the other staff items, the decision is made here, so nobody can equip it
-- by crafting a request, Pro and testing never include it, and it falls back
-- to the default by itself if the role is removed (the stored choice is
-- kept). The founder can't wear it either: it says who Jesse is.
--
-- Additive: widens one check constraint, adds 8 catalog rows, redefines two
-- functions with the same signatures, and puts the set on Jesse's profile
-- (only if his account exists and only in slots he hasn't chosen yet).
-- Safe to run more than once.
-- ============================================================================

alter table public.pro_catalog drop constraint if exists pro_catalog_unlock_check;
alter table public.pro_catalog add constraint pro_catalog_unlock_check
  check (unlock in ('free','pro','staff:admin','staff:owner')
         or unlock ~ '^milestone:[a-z_]+$'
         or unlock ~ '^staff:member:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$');

