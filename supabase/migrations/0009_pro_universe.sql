-- slot -> category. Public slots show on your profile and posts; the others
-- only change what you see.
create or replace function public.pro_slot_cat(p_slot text) returns text
language sql immutable as $$
  select case p_slot
    when 'ring' then 'ring' when 'banner' then 'banner' when 'nameplate' then 'nameplate' when 'badge' then 'badge'
    when 'layout' then 'layout' when 'milestone' then 'milestone' when 'theme' then 'theme' when 'effect' then 'effect'
    when 'reaction' then 'reaction' when 'chat' then 'chat' when 'sound' then 'sound' when 'feed' then 'feed'
    when 'dashboard' then 'dashboard' when 'insight' then 'insight' end
$$;

create table if not exists public.pro_equips (
  user_id uuid not null references public.profiles (id) on delete cascade,
  slot text not null check (public.pro_slot_cat(slot) is not null),
  item_id text not null references public.pro_catalog (id),
  updated_at timestamptz not null default now(),
  primary key (user_id, slot)
);

create table if not exists public.pro_milestones (
  user_id uuid not null references public.profiles (id) on delete cascade,
  key text not null check (key = any (public.pro_milestone_keys())),
  earned_at timestamptz not null default now(),
  primary key (user_id, key)
);

create table if not exists public.pro_wishlist (
  user_id uuid not null references public.profiles (id) on delete cascade,
  item_id text not null references public.pro_catalog (id),
  added_at timestamptz not null default now(),
