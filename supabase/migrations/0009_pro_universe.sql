-- Create (p_id null) or edit a draft. Published drafts are read-only.
create or replace function public.pro_save_draft(p_id uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  d public.pro_drafts;
  k text;
  opts text[];
  tpl text := nullif(p ->> 'template', '');
begin
  perform public.enforce_rate_limit('pro_drafts', 300, 3600);
  for k in select jsonb_object_keys(coalesce(p, '{}'::jsonb)) loop
    if k not in ('template','folder','kind','body','media_url','media_type','link_url','poll_options','plan') then
      raise exception 'INVALID|Unknown draft field: %', k;
    end if;
  end loop;
  if tpl is not null then
    if not exists (select 1 from public.pro_catalog where id = tpl and cat in ('draft','planner')) then raise exception 'INVALID|Unknown template.'; end if;
    if not public.pro_owns(v, tpl) then raise exception 'FORBIDDEN|That template is part of YORU Pro.' using errcode = '42501'; end if;
  end if;
  if not public.valid_media_path(p ->> 'media_url', v) then raise exception 'INVALID|You can only attach your own uploads.'; end if;
  if p ? 'poll_options' and jsonb_typeof(p -> 'poll_options') = 'array' then
    select array_agg(left(btrim(o), 80)) into opts from jsonb_array_elements_text(p -> 'poll_options') o;
    if cardinality(opts) > 6 then raise exception 'INVALID|Polls need 2 to 6 options.'; end if;
  end if;
  if p_id is null then
    if (select count(*) from public.pro_drafts where owner_id = v and status <> 'published')
       >= (case when public.is_pro(v) then 200 else 20 end) then
      raise exception 'INVALID|Your drafts are full. Delete or post some first.';
    end if;
    insert into public.pro_drafts (owner_id, template, folder, kind, body, media_url, media_type, link_url, poll_options, plan)
    values (v, tpl, left(coalesce(p ->> 'folder', ''), 40), coalesce(p ->> 'kind', 'post'), coalesce(p ->> 'body', ''),
            nullif(p ->> 'media_url', ''), nullif(p ->> 'media_type', ''), nullif(btrim(coalesce(p ->> 'link_url', '')), ''), opts,
            nullif(left(p ->> 'plan', 80), ''))
    returning * into d;
  else
    update public.pro_drafts set
      template = case when p ? 'template' then tpl else template end,
      folder = case when p ? 'folder' then left(coalesce(p ->> 'folder', ''), 40) else folder end,
      kind = coalesce(p ->> 'kind', kind),
      body = coalesce(p ->> 'body', body),
      media_url = case when p ? 'media_url' then nullif(p ->> 'media_url', '') else media_url end,
      media_type = case when p ? 'media_type' then nullif(p ->> 'media_type', '') else media_type end,
      link_url = case when p ? 'link_url' then nullif(btrim(coalesce(p ->> 'link_url', '')), '') else link_url end,
      poll_options = case when p ? 'poll_options' then opts else poll_options end,
      plan = case when p ? 'plan' then nullif(left(p ->> 'plan', 80), '') else plan end,
      -- editing a failed draft gives it another chance
      status = case when status = 'failed' then 'draft' else status end,
      error = case when status = 'failed' then null else error end,
      attempts = case when status = 'failed' then 0 else attempts end,
      updated_at = now()
    where id = p_id and owner_id = v and status <> 'published'
    returning * into d;
    if d.id is null then raise exception 'NOT_FOUND|That draft isn''t yours or was already posted.' using errcode = 'P0002'; end if;
  end if;
  return public.pro_draft_json(d);
end $$;

