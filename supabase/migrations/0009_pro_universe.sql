end $$;

-- ---------------------------------------------------------------------------
-- Settings. Every key is validated; anything that unlocks a Pro feature is
-- still checked where it's used.
-- ---------------------------------------------------------------------------

create or replace function public.pro_clean_words(p jsonb, p_max int, p_len int) returns jsonb
language sql immutable as $$
  select coalesce(jsonb_agg(w), '[]'::jsonb) from (
    select distinct lower(btrim(w)) as w from jsonb_array_elements_text(case when jsonb_typeof(p) = 'array' then p else '[]'::jsonb end) w
    where char_length(btrim(w)) between 1 and p_len limit p_max
  ) x
$$;

create or replace function public.pro_save_settings(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  cur jsonb := coalesce((select data from public.pro_settings where user_id = v), '{}'::jsonb);
  k text;
  val jsonb;
  out jsonb;
  sections text[] := array['stats','xp','showcase','interests','achievements','jokes','timeline','collections','pinned','tabs'];
  widgets text[] := array['kpis','reach','engagement','new_engagers','compare','types','week','month','top','recent','timeline',
    'hours','visits','reaction_kinds','comments','consistency','history','type_perf','summary','milestones','bests','range','growth'];
begin
  perform public.enforce_rate_limit('pro_settings', 120, 3600);
  if jsonb_typeof(p) <> 'object' then raise exception 'INVALID|Settings must be an object.'; end if;
  for k, val in select * from jsonb_each(p) loop
    case k
      when 'labs' then
        -- only lab tools that exist; turning one on is a preference, not an unlock
        cur := cur || jsonb_build_object(k, coalesce((select jsonb_agg(x) from (
          select distinct x from jsonb_array_elements_text(val) x
          where exists (select 1 from public.pro_catalog c where c.id = x and c.cat = 'lab')) y), '[]'::jsonb));
      when 'sound_volume' then
        cur := cur || jsonb_build_object(k, least(greatest(coalesce((val #>> '{}')::int, 60), 0), 100));
      when 'sounds_on', 'show_timeline', 'effects_on', 'ring_motion' then
        cur := cur || jsonb_build_object(k, coalesce((val #>> '{}')::boolean, false));
      when 'layout_order' then
        cur := cur || jsonb_build_object(k, coalesce((select jsonb_agg(x order by o) from (
          select distinct on (x) x, o from jsonb_array_elements_text(val) with ordinality t(x, o) where x = any (sections) order by x, o) y), '[]'::jsonb));
      when 'dashboard_widgets', 'insight_widgets' then
        cur := cur || jsonb_build_object(k, coalesce((select jsonb_agg(x order by o) from (
          select distinct on (x) x, o from jsonb_array_elements_text(val) with ordinality t(x, o) where x = any (widgets) order by x, o limit 12) y), '[]'::jsonb));
      when 'muted_words' then
        cur := cur || jsonb_build_object(k, public.pro_clean_words(val, 50, 40));
      when 'hub_tags' then
        cur := cur || jsonb_build_object(k, (select coalesce(jsonb_agg(w), '[]'::jsonb) from jsonb_array_elements_text(public.pro_clean_words(val, 12, 30)) w
                                              where w ~ '^[[:alnum:]_]+$'));
      when 'pinned_hubs' then
        cur := cur || jsonb_build_object(k, coalesce((select jsonb_agg(x) from (
          select distinct x from jsonb_array_elements_text(val) x
          where exists (select 1 from public.pro_catalog c where c.id = x and c.cat = 'hub') and public.pro_owns(v, x) limit 8) y), '[]'::jsonb));
      when 'feed_custom' then
        if jsonb_typeof(val) <> 'object' then raise exception 'INVALID|Custom feed must be an object.'; end if;
        cur := cur || jsonb_build_object(k, jsonb_strip_nulls(jsonb_build_object(
          'sort', case when val ->> 'sort' in ('latest','top') then val ->> 'sort' else 'latest' end,
          'media', case when val ->> 'media' in ('any','image','video','text') then val ->> 'media' end,
          'tags', (select coalesce(jsonb_agg(w), '[]'::jsonb) from jsonb_array_elements_text(public.pro_clean_words(val -> 'tags', 12, 30)) w where w ~ '^[[:alnum:]_]+$'),
          'kinds', (select jsonb_agg(x) from jsonb_array_elements_text(case when jsonb_typeof(val -> 'kinds') = 'array' then val -> 'kinds' else '[]' end) x
                    where x in ('post','poll','repost','news','roast')),
          'days', case when (val ->> 'days') ~ '^[0-9]{1,3}$' then least((val ->> 'days')::int, 90) end,
          'muted', coalesce((val ->> 'muted')::boolean, false))));
      else
        raise exception 'INVALID|Unknown setting: %', k;
    end case;
  end loop;
  insert into public.pro_settings (user_id, data) values (v, cur)
  on conflict (user_id) do update set data = excluded.data, updated_at = now()
  returning data into out;
  return out;
end $$;

