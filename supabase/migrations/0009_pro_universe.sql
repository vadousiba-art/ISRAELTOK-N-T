create or replace function public.profile_lite(p public.profiles) returns jsonb
language sql stable as $$
  select jsonb_build_object(
    'id', p.id, 'username', p.username, 'display_name', p.display_name,
    'avatar_url', p.avatar_url, 'badge', p.badge, 'verified', p.verified,
    'is_bot', p.is_bot, 'role', p.role, 'status', p.status,
    'online', p.is_bot or (not p.ghost_mode and coalesce(p.last_seen_at > now() - interval '5 minutes', false)),
    'level', public.level_for(p.xp), 'accent_hue', p.accent_hue, 'flair', p.flair,
    'creator', p.creator_category, 'frame', public.effective_frame(p.id, p.avatar_frame),
    'look', public.pro_public_look(p.id)
  )
$$;

create or replace function public.get_profile_identity(p_username text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  p public.profiles;
  st jsonb;
begin
  select * into p from public.profiles where lower(username) = lower(p_username);
  if p.id is null or (p.banned and not public.is_admin()) or public.is_hidden_author(p.id) then
    raise exception 'NOT_FOUND|No such member.' using errcode = 'P0002';
  end if;
  st := coalesce((select data from public.pro_settings where user_id = p.id), '{}'::jsonb);
  return jsonb_build_object(
    'interests', to_jsonb(p.interests),
    'banner_style', public.effective_banner(p.id, p.banner_style),
    'avatar_frame', public.effective_frame(p.id, p.avatar_frame),
    'showcase_badges', to_jsonb(p.showcase_badges),
    'creator_category', p.creator_category, 'creator_since', p.creator_since,
    'pro', public.is_pro(p.id),
    'ghost_mode', case when p.id = v then p.ghost_mode else null end,
    'collections', coalesce((
      select jsonb_agg(public.collection_json(c, v) order by c.updated_at desc)
      from public.collections c
      where c.owner_id = p.id and (c.owner_id = v or c.visibility = 'members')
    ), '[]'::jsonb),
    'look', jsonb_strip_nulls(jsonb_build_object(
      'ring', public.pro_effective(p.id, 'ring'),
      'banner', public.pro_effective(p.id, 'banner'),
      'nameplate', public.pro_effective(p.id, 'nameplate'),
      'badge', public.pro_effective(p.id, 'badge'),
      'layout', public.pro_effective(p.id, 'layout'),
      'milestone', public.pro_effective(p.id, 'milestone'),
      'layout_order', case when public.pro_effective(p.id, 'layout') = 'layout.custom_canvas' then st -> 'layout_order' end)),
    'timeline', case when coalesce((st ->> 'show_timeline')::boolean, true) then coalesce((
      select jsonb_agg(jsonb_build_object('key', key, 'earned_at', earned_at) order by earned_at)
      from public.pro_milestones where user_id = p.id), '[]'::jsonb) else '[]'::jsonb end
  );
end $$;

-- ---------------------------------------------------------------------------
-- Scheduler: pg_cron every minute where the extension exists (Supabase).
-- Elsewhere /api/cron/publish (service role) calls pro_publish_due().
-- ---------------------------------------------------------------------------

do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    begin
      create extension if not exists pg_cron;
      perform cron.schedule('yoru-pro-publish', '* * * * *', 'select public.pro_publish_due(50, ''pg_cron'')');
    exception when others then
      raise notice 'pg_cron not set up: %', sqlerrm;
    end;
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Grants
-- ---------------------------------------------------------------------------

do $$
declare f text;
begin
  -- helpers: members may call them (they only answer about ownership), anon may not
  foreach f in array array[
    'pro_universe_version()', 'pro_milestone_keys()', 'pro_slot_cat(text)', 'pro_public_look(uuid)', 'pro_milestone_goal(text)', 'pro_clean_words(jsonb, int, int)', 'pro_draft_json(public.pro_drafts)'
  ] loop
    execute format('revoke execute on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated, service_role', f);
  end loop;
  -- internal: never callable by members
  foreach f in array array[
    'pro_owns(uuid, text)', 'pro_effective(uuid, text)', 'pro_milestone_progress(uuid)', 'pro_sync_milestones(uuid)', 'pro_membership(uuid)', 'pro_check_equip(uuid, text, text)',
    'pro_publish_due(int, text)'
  ] loop
    execute format('revoke execute on function public.%s from public, anon, authenticated', f);
    execute format('grant execute on function public.%s to service_role', f);
  end loop;
  -- member RPCs
  foreach f in array array[
    'get_my_pro()', 'pro_equip(text, text)', 'pro_equip_many(jsonb)', 'pro_reset_look()', 'pro_wishlist_toggle(text)',
    'pro_save_settings(jsonb)', 'pro_get_drafts()', 'pro_save_draft(uuid, jsonb)', 'pro_delete_draft(uuid)',
    'pro_schedule_draft(uuid, timestamptz, text)', 'pro_record_profile_view(text)', 'get_creator_analytics(date, date)',
    'get_feed_preset(text, int, int, boolean)', 'get_hub(text, timestamptz, int)', 'pro_style_collection(uuid, text, text)',
    'get_collection_page(uuid, int, int)', 'get_profile_identity(text)'
  ] loop
    execute format('revoke execute on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated, service_role', f);
  end loop;
end $$;
