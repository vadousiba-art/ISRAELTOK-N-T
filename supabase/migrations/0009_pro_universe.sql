);

create table if not exists public.pro_settings (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  data jsonb not null default '{}'::jsonb check (pg_column_size(data) <= 8192),
  updated_at timestamptz not null default now()
);

create table if not exists public.pro_drafts (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  template text references public.pro_catalog (id),
  folder text not null default '' check (char_length(folder) <= 40),
  kind text not null default 'post' check (kind in ('post','poll')),
  body text not null default '' check (char_length(body) <= 2000),
  media_url text check (media_url is null or char_length(media_url) <= 300),
  media_type text check (media_type is null or media_type in ('image','video','gif')),
  link_url text check (link_url is null or (link_url ~ '^https?://' and char_length(link_url) <= 500)),
  poll_options text[] check (poll_options is null or cardinality(poll_options) <= 6),
  status text not null default 'draft' check (status in ('draft','scheduled','published','failed')),
  scheduled_at timestamptz,
  timezone text check (timezone is null or char_length(timezone) <= 64),
  plan text check (plan is null or char_length(plan) <= 80),
  attempts int not null default 0,
  error text check (error is null or char_length(error) <= 300),
  post_id uuid references public.posts (id) on delete set null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status <> 'scheduled' or scheduled_at is not null)
);
create index if not exists pro_drafts_owner_idx on public.pro_drafts (owner_id, updated_at desc);
create index if not exists pro_drafts_due_idx on public.pro_drafts (scheduled_at) where status = 'scheduled';

