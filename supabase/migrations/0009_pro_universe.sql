create or replace function public.pro_wishlist_toggle(p_item text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
begin
  perform public.enforce_rate_limit('pro_wishlist', 300, 3600);
