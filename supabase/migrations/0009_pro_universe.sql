  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Creator Analytics + Profile Insights: the caller's own numbers only. Your
-- own reactions and comments are never counted. Nothing is estimated.
-- ---------------------------------------------------------------------------

create or replace function public.get_creator_analytics(p_from date default null, p_to date default null) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  me public.profiles;
  rfrom date := coalesce(p_from, (now() at time zone 'utc')::date - 29);
  rto date := coalesce(p_to, (now() at time zone 'utc')::date);
  res jsonb;
begin
  select * into me from public.profiles where id = v;
  if rto < rfrom or rto - rfrom > 366 then raise exception 'INVALID|Pick a range up to a year.'; end if;
  with own as (
    select p.* from public.posts p where p.author_id = v and p.deleted_at is null and p.kind <> 'repost'
  ), ev as (
    select r.post_id, r.user_id, r.created_at, 'reaction'::text as t, r.kind from public.reactions r join own on own.id = r.post_id where r.user_id <> v
    union all
    select c.post_id, c.author_id, c.created_at, 'comment', null from public.comments c join own on own.id = c.post_id
    where c.author_id <> v and c.deleted_at is null and not c.is_ai
  ), firsts as (
    select user_id, min(created_at) as first_at from ev group by user_id
  ), weeks as (
    select generate_series(date_trunc('week', now()) - interval '11 weeks', date_trunc('week', now()), interval '1 week') as w
  ), days as (
    select generate_series((now() at time zone 'utc')::date - 29, (now() at time zone 'utc')::date, interval '1 day')::date as d
  ), per_post as (
    select own.id, own.body, own.kind, own.media_type, own.created_at,
      (select count(*) from ev where ev.post_id = own.id and ev.t = 'reaction') as reactions,
      (select count(*) from ev where ev.post_id = own.id and ev.t = 'comment') as comments
    from own
  ), win as (
    select n, (select count(*) from ev where ev.created_at > now() - make_interval(days => n) and ev.t = 'reaction') as r_now,
              (select count(*) from ev where ev.created_at between now() - make_interval(days => 2 * n) and now() - make_interval(days => n) and ev.t = 'reaction') as r_prev,
              (select count(*) from ev where ev.created_at > now() - make_interval(days => n) and ev.t = 'comment') as c_now,
              (select count(*) from ev where ev.created_at between now() - make_interval(days => 2 * n) and now() - make_interval(days => n) and ev.t = 'comment') as c_prev,
              (select count(*) from own where own.created_at > now() - make_interval(days => n)) as p_now,
              (select count(*) from own where own.created_at between now() - make_interval(days => 2 * n) and now() - make_interval(days => n)) as p_prev,
              (select count(distinct user_id) from ev where ev.created_at > now() - make_interval(days => n)) as e_now,
              (select count(distinct user_id) from ev where ev.created_at between now() - make_interval(days => 2 * n) and now() - make_interval(days => n)) as e_prev,
              (select coalesce(sum(views), 0) from public.pro_profile_views where profile_id = v and day > (now() at time zone 'utc')::date - n) as v_now,
              (select coalesce(sum(views), 0) from public.pro_profile_views where profile_id = v
                 and day <= (now() at time zone 'utc')::date - n and day > (now() at time zone 'utc')::date - 2 * n) as v_prev
    from unnest(array[7, 30, 90]) n
  )
  select jsonb_build_object(
    'generated_at', now(),
    'member_since', me.created_at,
    'visits_counted_since', (select min(day) from public.pro_profile_views where profile_id = v),
    'kpis', jsonb_build_object(
      'posts', (select count(*) from own),
      'reactions', (select count(*) from ev where t = 'reaction'),
      'comments', (select count(*) from ev where t = 'comment'),
      'engagers', (select count(distinct user_id) from ev),
      'bookmarks', (select count(*) from public.bookmarks b join own on own.id = b.post_id where b.user_id <> v),
      'collection_saves', (select count(*) from public.collection_items i join own on own.id = i.post_id
                           join public.collections c on c.id = i.collection_id where c.owner_id <> v),
      'reposts', (select count(*) from public.posts rp join own on own.id = rp.repost_of where rp.deleted_at is null and rp.author_id <> v),
      'visits_30d', (select coalesce(sum(views), 0) from public.pro_profile_views where profile_id = v and day > (now() at time zone 'utc')::date - 30),
      'best_streak', me.best_streak, 'streak', me.streak),
    'weekly', (select jsonb_agg(jsonb_build_object(
        'week', weeks.w::date,
        'posts', (select count(*) from own where date_trunc('week', own.created_at) = weeks.w),
        'reactions', (select count(*) from ev where ev.t = 'reaction' and date_trunc('week', ev.created_at) = weeks.w),
        'comments', (select count(*) from ev where ev.t = 'comment' and date_trunc('week', ev.created_at) = weeks.w),
        'engagers', (select count(distinct user_id) from ev where date_trunc('week', ev.created_at) = weeks.w),
        'new_engagers', (select count(*) from firsts where date_trunc('week', firsts.first_at) = weeks.w),
        'visits', (select coalesce(sum(views), 0) from public.pro_profile_views where profile_id = v and date_trunc('week', day::timestamptz) = weeks.w)
      ) order by weeks.w) from weeks),
    'daily', (select jsonb_agg(jsonb_build_object(
        'day', days.d,
        'reactions', (select count(*) from ev where ev.t = 'reaction' and (ev.created_at at time zone 'utc')::date = days.d),
        'comments', (select count(*) from ev where ev.t = 'comment' and (ev.created_at at time zone 'utc')::date = days.d),
        'posts', (select count(*) from own where (own.created_at at time zone 'utc')::date = days.d)
      ) order by days.d) from days),
    'hours', case when (select count(*) from ev where ev.created_at > now() - interval '90 days') < 20 then null else
      (select jsonb_agg(coalesce(x.n, 0) order by h) from generate_series(0, 23) h
       left join (select extract(hour from created_at at time zone 'utc')::int as hr, count(*) as n from ev
                  where ev.created_at > now() - interval '90 days' group by 1) x on x.hr = h) end,
    'reaction_kinds', coalesce((select jsonb_object_agg(kind, n) from (select kind, count(*) n from ev where t = 'reaction' group by kind) x), '{}'::jsonb),
    'types', coalesce((select jsonb_object_agg(t, jsonb_build_object('posts', n, 'avg_reactions', ar, 'avg_comments', ac)) from (
        select case when kind = 'poll' then 'poll' when media_type is null then 'text' else media_type end as t,
               count(*) n, round(avg(reactions), 2) ar, round(avg(comments), 2) ac
        from per_post group by 1) x), '{}'::jsonb),
    'top', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'body', left(body, 140), 'kind', kind, 'media_type', media_type,
        'created_at', created_at, 'reactions', reactions, 'comments', comments) order by reactions + comments desc, created_at desc)
      from (select * from per_post where reactions + comments > 0 order by reactions + comments desc, created_at desc limit 5) t), '[]'::jsonb),
    'recent', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'body', left(body, 140), 'kind', kind, 'media_type', media_type,
        'created_at', created_at, 'reactions', reactions, 'comments', comments) order by created_at desc)
      from (select * from per_post order by created_at desc limit 5) t), '[]'::jsonb),
    'posts', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'body', left(body, 80), 'created_at', created_at,
        'reactions', reactions, 'comments', comments) order by created_at desc)
      from (select * from per_post order by created_at desc limit 50) t), '[]'::jsonb),
    'consistency', coalesce((select jsonb_agg(distinct (created_at at time zone 'utc')::date) from own
                             where created_at > now() - interval '84 days'), '[]'::jsonb),
    'windows', (select jsonb_object_agg(n, jsonb_build_object(
        'reactions', jsonb_build_array(r_now, r_prev), 'comments', jsonb_build_array(c_now, c_prev),
        'posts', jsonb_build_array(p_now, p_prev), 'engagers', jsonb_build_array(e_now, e_prev),
        'visits', jsonb_build_array(v_now, v_prev))) from win),
    'bests', jsonb_build_object(
      'post', (select jsonb_build_object('id', id, 'body', left(body, 140), 'reactions', reactions, 'comments', comments)
               from per_post where reactions + comments > 0 order by reactions + comments desc, created_at limit 1),
      'week', (select jsonb_build_object('week', w, 'engagement', n) from (
                 select date_trunc('week', created_at)::date w, count(*) n from ev group by 1 order by n desc, w desc limit 1) x),
      'streak', me.best_streak),
    'range', jsonb_build_object('from', rfrom, 'to', rto,
      'posts', (select count(*) from own where (created_at at time zone 'utc')::date between rfrom and rto),
      'reactions', (select count(*) from ev where t = 'reaction' and (created_at at time zone 'utc')::date between rfrom and rto),
      'comments', (select count(*) from ev where t = 'comment' and (created_at at time zone 'utc')::date between rfrom and rto),
      'engagers', (select count(distinct user_id) from ev where (created_at at time zone 'utc')::date between rfrom and rto),
      'visits', (select coalesce(sum(views), 0) from public.pro_profile_views where profile_id = v and day between rfrom and rto))
  ) into res;
  return res;
end $$;

-- ---------------------------------------------------------------------------
-- Feed presets (Advanced Feed Controls). Filters and sorts what you see;
-- nobody's ranking or reach changes. Owning the preset is checked here; a
-- preview (p_preview) shows the first 5 posts so you can try before equipping.
-- ---------------------------------------------------------------------------

create or replace function public.get_feed_preset(
  p_preset text, p_offset int default 0, p_limit int default 15, p_preview boolean default false
) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  me public.profiles;
  c public.pro_catalog;
  f jsonb;
  tags text[];
  kinds text[];
  muted text[];
  lim int := least(greatest(coalesce(p_limit, 15), 1), 50);
  off int := greatest(coalesce(p_offset, 0), 0);
  res jsonb;
begin
  select * into c from public.pro_catalog where id = p_preset and cat = 'feed' and status <> 'retired';
  if c.id is null then raise exception 'NOT_FOUND|No such feed.' using errcode = 'P0002'; end if;
  if not public.pro_owns(v, c.id) then
    if not p_preview then raise exception 'FORBIDDEN|That feed is part of YORU Pro.' using errcode = '42501'; end if;
    lim := least(lim, 5); off := 0;
  end if;
  select * into me from public.profiles where id = v;
  f := c.p;
  if coalesce((f ->> 'custom')::boolean, false) then
    f := coalesce((select data -> 'feed_custom' from public.pro_settings where user_id = v), '{}'::jsonb);
  end if;
  tags := (select array_agg(x) from jsonb_array_elements_text(coalesce(f -> 'tags', '[]')) x);
  kinds := (select array_agg(x) from jsonb_array_elements_text(coalesce(f -> 'kinds', '[]')) x);
  if coalesce((f ->> 'muted')::boolean, false) then
    muted := (select array_agg(replace(replace(replace(x, '\', '\\'), '%', '\%'), '_', '\_'))
              from jsonb_array_elements_text(coalesce((select data -> 'muted_words' from public.pro_settings where user_id = v), '[]')) x);
  end if;

  select coalesce(jsonb_agg(public.post_json(p, v) order by s.rank), '[]'::jsonb) into res from (
    select p.id, row_number() over (order by
        case when f ->> 'authors' = 'interacted' and exists (select 1 from public.reactions r2 join public.posts p2 on p2.id = r2.post_id
              where r2.user_id = v and p2.author_id = p.author_id) then 0 else 1 end,
        case when f ->> 'sort' = 'top' then
          -((select count(*) from public.reactions r where r.post_id = p.id) + 2 * (select count(*) from public.comments cm where cm.post_id = p.id and cm.deleted_at is null))
        else 0 end,
        p.created_at desc) as rank
    from public.posts p join public.profiles a on a.id = p.author_id
    where p.deleted_at is null and not public.is_hidden_author(p.author_id)
      and (case when kinds is not null then p.kind = any (kinds) else p.kind <> 'repost' end)
      and (tags is null or p.hashtags && tags)
      and (not coalesce((f ->> 'interests')::boolean, false) or p.hashtags && me.interests or a.interests && me.interests)
      and (case f ->> 'media' when 'image' then p.media_type in ('image','gif') when 'video' then p.media_type = 'video'
             when 'text' then p.media_url is null else true end)
      and (case f ->> 'authors'
             when 'new' then a.created_at > now() - interval '30 days'
             when 'active' then not a.ghost_mode and a.last_seen_at > now() - interval '1 day'
             when 'creators' then a.creator_category is not null
             when 'interacted' then p.created_at > now() - interval '30 days'
             else true end)
      and (f ->> 'days' is null or p.created_at > now() - make_interval(days => (f ->> 'days')::int))
      and (muted is null or not exists (select 1 from unnest(muted) w where p.body ilike '%' || w || '%'))
      and (coalesce(f ->> 'sort', 'latest') <> 'top' or p.created_at > now() - interval '30 days')
    order by rank offset off limit lim
  ) s join public.posts p on p.id = s.id;
  return res;
end $$;

