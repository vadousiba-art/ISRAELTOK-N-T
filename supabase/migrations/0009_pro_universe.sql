-- ---------------------------------------------------------------------------
-- Milestones: progress from the member's own records. Earned once, kept.
-- ---------------------------------------------------------------------------

create or replace function public.pro_milestone_progress(p_user uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  with me as (select * from public.profiles where id = p_user),
  own as (select * from public.posts where author_id = p_user and deleted_at is null and kind <> 'repost')
  select jsonb_build_object(
    'first_night', (select count(*) from own),
    'first_collection', (select count(*) from public.collections where owner_id = p_user),
    'creators_mark', (select (creator_category is not null)::int from me),
    'midnight_milestone', (select best_streak from me),
    'ink_explorer', (select count(distinct t) from own, unnest(own.hashtags) t),
    'digital_pioneer', (select count(*) from own where media_url is not null),
    'music_enthusiast', (select count(*) from own where hashtags && array['music','vocaloid','jpop','jrock']),
    'art_collector', (select count(distinct i.post_id) from public.collection_items i
                      join public.collections c on c.id = i.collection_id and c.owner_id = p_user
                      join public.posts p on p.id = i.post_id and p.media_type = 'image'),
    'community_regular', (select count(*) from public.comments cm join public.posts p on p.id = cm.post_id
                          where cm.author_id = p_user and cm.deleted_at is null and p.author_id <> p_user),
    'night_archivist', (select count(*) from public.bookmarks where user_id = p_user),
    'creative_streak', (select count(distinct (created_at at time zone 'utc')::date) from own),
    'profile_builder', (select (avatar_url is not null)::int + (coalesce(bio, '') <> '')::int + (cardinality(interests) > 0)::int from me),
    'discovery_journey', (select count(distinct p.author_id) from public.reactions r join public.posts p on p.id = r.post_id
                          where r.user_id = p_user and p.author_id <> p_user),
    'collection_curator', (select count(*) from public.collections c where c.owner_id = p_user
                           and (select count(*) from public.collection_items i where i.collection_id = c.id) >= 5),
    'creator_milestone', (select count(*) from public.reactions r join own on own.id = r.post_id where r.user_id <> p_user),
    'personal_archive', (select count(*) from own),
    'seasonal_journey', (select count(distinct date_trunc('month', created_at at time zone 'utc')) from own),
    'year_in_yoru', (select case when exists (select 1 from own where created_at > now() - interval '1 year')
                                 then least(365, floor(extract(epoch from now() - created_at) / 86400))::int else 0 end from me),
    'legacy_display', (select count(*) from public.pro_milestones where user_id = p_user and key not in ('legacy_display','eternal_night')),
    'eternal_night', (select count(*) from public.pro_milestones where user_id = p_user and key <> 'eternal_night')
  )
$$;

create or replace function public.pro_milestone_goal(p_key text) returns int
language sql immutable as $$
  select case p_key
    when 'midnight_milestone' then 7 when 'ink_explorer' then 5 when 'digital_pioneer' then 3 when 'music_enthusiast' then 3
    when 'art_collector' then 10 when 'community_regular' then 25 when 'night_archivist' then 25 when 'creative_streak' then 7
    when 'profile_builder' then 3 when 'discovery_journey' then 10 when 'collection_curator' then 3
    when 'creator_milestone' then 100 when 'personal_archive' then 50 when 'seasonal_journey' then 3
    when 'year_in_yoru' then 365 when 'legacy_display' then 10 when 'eternal_night' then 19 else 1 end
$$;

-- Records any milestone the member has reached. Two passes so the two
-- "earn N others" milestones see the ones just earned.
create or replace function public.pro_sync_milestones(p_user uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  prog jsonb;
  pass int;
begin
  for pass in 1..3 loop
    prog := public.pro_milestone_progress(p_user);
    insert into public.pro_milestones (user_id, key)
    select p_user, k from unnest(public.pro_milestone_keys()) k
    where coalesce((prog ->> k)::int, 0) >= public.pro_milestone_goal(k)
    on conflict do nothing;
    exit when not found;
  end loop;
  return prog;
end $$;

