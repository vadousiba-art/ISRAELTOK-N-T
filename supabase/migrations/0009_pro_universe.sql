-- ============================================================================
-- YORU — Pro Universe (catalog v1). docs/pro-universe.md
--
-- The 400-item Pro catalog, server side:
--   * pro_catalog      ids, categories and unlock rules (free / pro / earned),
--                      generated from src/lib/pro/catalog (a test compares them)
--   * pro_equips       one item per slot; ownership is checked here, never in
--                      the browser. While someone isn't Pro, Pro items fall back
--                      to the default; the stored choice is kept for renewal.
--   * pro_milestones   Profile Evolution, earned from the member's own records
--   * pro_wishlist, pro_settings
--   * pro_drafts       Draft Studio + Post Planner. Scheduled drafts are
--                      published by pro_publish_due() through create_post(), as
--                      the author, so every normal rule applies. pg_cron runs it
--                      every minute where available; /api/cron/publish can too.
--                      Scheduling is refused while no scheduler is running.
--   * pro_profile_views  aggregate daily visit counts. Viewers are never stored
--                      in readable form and never shown to anyone.
--   * analytics, insights, feed presets, interest hubs and collection styles
--                      read only the caller's own or already-visible data.
--
-- Additive and backward-compatible: new tables (RLS on, reads only, writes via
-- checked functions), new nullable/defaulted columns on collections, new
-- functions. Existing functions keep their signatures; profile_lite and
-- get_profile_identity gain fields. Safe to run more than once.
-- No payments: Pro still comes only from entitlements (admin comp grants).
-- ============================================================================

