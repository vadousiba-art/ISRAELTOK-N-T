create or replace function public.pro_style_collection(p_id uuid, p_template text default null, p_sort text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  c public.collections;
begin
  perform public.enforce_rate_limit('collections', 60, 3600);
