-- Schedule (p_at) or unschedule (p_at null). Refused while no scheduler is
-- running, so the planner never claims something will be posted when it won't.
create or replace function public.pro_schedule_draft(p_id uuid, p_at timestamptz default null, p_timezone text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  d public.pro_drafts;
begin
  perform public.enforce_rate_limit('pro_schedule', 120, 3600);
  select * into d from public.pro_drafts where id = p_id and owner_id = v for update;
  if d.id is null or d.status = 'published' then
    raise exception 'NOT_FOUND|That draft isn''t yours or was already posted.' using errcode = 'P0002';
  end if;
  if p_at is null then
    update public.pro_drafts set status = 'draft', scheduled_at = null, updated_at = now() where id = p_id returning * into d;
    return public.pro_draft_json(d);
  end if;
  if not exists (select 1 from public.pro_scheduler where last_run > now() - interval '15 minutes') then
    raise exception 'UNAVAILABLE|Scheduling isn''t running right now. Your draft is saved; post it yourself or try again later.';
  end if;
  if p_at < now() + interval '1 minute' or p_at > now() + interval '180 days' then
    raise exception 'INVALID|Pick a time between a minute and 180 days from now.';
  end if;
  if btrim(d.body) = '' and d.media_url is null then raise exception 'INVALID|Write something first.'; end if;
  if d.kind = 'poll' and (d.poll_options is null or cardinality(d.poll_options) < 2) then raise exception 'INVALID|Polls need 2 to 6 options.'; end if;
  if (select count(*) from public.pro_drafts where owner_id = v and status = 'scheduled' and id <> p_id)
     >= (case when public.is_pro(v) then 50 else 3 end) then
    raise exception 'INVALID|You''ve reached your scheduled-post limit.';
  end if;
  update public.pro_drafts set status = 'scheduled', scheduled_at = p_at, timezone = nullif(left(p_timezone, 64), ''),
    attempts = 0, error = null, updated_at = now()
  where id = p_id returning * into d;
  return public.pro_draft_json(d);
end $$;

-- Publish drafts whose time has come. Runs as each author through
-- create_post(), so mutes, bans, lockdown, slow mode, rate limits, media
-- ownership and poll rules all apply exactly as when posting by hand.
-- Up to 3 attempts, 5 minutes apart, then the draft is marked failed with the
-- reason. Server only (pg_cron or the service role).
create or replace function public.pro_publish_due(p_limit int default 50, p_runner text default 'cron') returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  d public.pro_drafts;
  new_id uuid;
  ok int := 0;
  bad int := 0;
  msg text;
begin
  for d in select * from public.pro_drafts where status = 'scheduled' and scheduled_at <= now()
           order by scheduled_at limit least(greatest(coalesce(p_limit, 50), 1), 200) for update skip locked loop
    begin
      perform set_config('request.jwt.claims', jsonb_build_object('sub', d.owner_id, 'role', 'authenticated')::text, true);
      new_id := public.create_post(d.body, d.media_url, d.media_type, d.link_url,
                                   case when d.kind = 'poll' then d.poll_options end);
      update public.pro_drafts set status = 'published', post_id = new_id, published_at = now(), error = null, updated_at = now()
      where id = d.id;
      ok := ok + 1;
    exception when others then
      msg := coalesce(nullif(split_part(sqlerrm, '|', 2), ''), 'Something went wrong.');
      update public.pro_drafts set
        attempts = attempts + 1,
        status = case when attempts + 1 >= 3 then 'failed' else 'scheduled' end,
        scheduled_at = case when attempts + 1 >= 3 then scheduled_at else now() + interval '5 minutes' end,
        error = left(msg, 300), updated_at = now()
      where id = d.id;
      bad := bad + 1;
    end;
    perform set_config('request.jwt.claims', '', true);
  end loop;
  update public.pro_scheduler set last_run = now(), runner = left(coalesce(p_runner, 'cron'), 20),
    published = published + ok, failed = failed + bad where id;
  delete from public.pro_profile_view_seen where day < (now() at time zone 'utc')::date - 1;
  return jsonb_build_object('published', ok, 'retrying_or_failed', bad);
end $$;

