  profile_id uuid not null references public.profiles (id) on delete cascade,
  day date not null,
  views int not null default 0,
  primary key (profile_id, day)
);
create table if not exists public.pro_profile_view_seen (
  day date not null,
  h text not null,
  primary key (day, h)
);

