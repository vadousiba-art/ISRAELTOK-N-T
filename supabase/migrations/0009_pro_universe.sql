create or replace function public.pro_check_equip(v uuid, p_slot text, p_item text) returns void
language plpgsql stable security definer set search_path = public as $$
declare
  c public.pro_catalog;
begin
  if public.pro_slot_cat(p_slot) is null then raise exception 'INVALID|Unknown slot.'; end if;
  select * into c from public.pro_catalog where id = p_item;
  if c.id is null or c.status = 'retired' then raise exception 'NOT_FOUND|No such item.' using errcode = 'P0002'; end if;
  if c.cat <> public.pro_slot_cat(p_slot) then raise exception 'INVALID|That item doesn''t go in that slot.'; end if;
  if not public.pro_owns(v, p_item) then
    if c.unlock = 'pro' then raise exception 'FORBIDDEN|That item is part of YORU Pro.' using errcode = '42501'; end if;
    raise exception 'FORBIDDEN|Earn this one first.' using errcode = '42501';
  end if;
  if c.status = 'experimental' and not coalesce((select data -> 'labs' ? 'lab.experimental_effects' from public.pro_settings where user_id = v), false) then
    raise exception 'FORBIDDEN|Turn on Experimental Effects in the Preview Lab first.' using errcode = '42501';
  end if;
end $$;

create or replace function public.pro_equip(p_slot text, p_item text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
begin
  perform public.enforce_rate_limit('pro_equip', 300, 3600);
  if p_item is null then
    if public.pro_slot_cat(p_slot) is null then raise exception 'INVALID|Unknown slot.'; end if;
    delete from public.pro_equips where user_id = v and slot = p_slot;
  else
    perform public.pro_check_equip(v, p_slot, p_item);
    insert into public.pro_equips (user_id, slot, item_id) values (v, p_slot, p_item)
    on conflict (user_id, slot) do update set item_id = excluded.item_id, updated_at = now();
  end if;
  return coalesce((select jsonb_object_agg(e.slot, jsonb_build_object('item', e.item_id, 'active', public.pro_owns(v, e.item_id)))
                   from public.pro_equips e where e.user_id = v), '{}'::jsonb);
end $$;

-- A whole look in one go ({slot: item}). Items you don't own are skipped and
-- listed; nothing is charged and nothing is unlocked by equipping a bundle.
create or replace function public.pro_equip_many(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  k text;
  skipped text[] := '{}';
begin
  perform public.enforce_rate_limit('pro_equip', 300, 3600);
  if jsonb_typeof(p) <> 'object' or (select count(*) from jsonb_object_keys(p)) > 14 then
    raise exception 'INVALID|Send a set of slots.';
  end if;
  for k in select jsonb_object_keys(p) loop
    begin
      perform public.pro_check_equip(v, k, p ->> k);
      insert into public.pro_equips (user_id, slot, item_id) values (v, k, p ->> k)
      on conflict (user_id, slot) do update set item_id = excluded.item_id, updated_at = now();
    exception when others then
      skipped := skipped || (p ->> k);
    end;
  end loop;
  return jsonb_build_object('skipped', to_jsonb(skipped));
end $$;

