create or replace function public.pro_membership(p_user uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'pro', public.is_pro(p_user),
    'status', case
      when public.is_pro(p_user) then
        case when exists (select 1 from public.entitlements e where e.user_id = p_user and e.status = 'active' and e.source = 'comp'
                          and e.starts_at <= now() and (e.ends_at is null or e.ends_at > now())) then 'comp' else 'active' end
      when exists (select 1 from public.entitlements e where e.user_id = p_user) then 'expired'
      else 'none' end,
    'until', (select max(coalesce(ends_at, 'infinity'::timestamptz)) from public.entitlements
              where user_id = p_user and status = 'active' and starts_at <= now() and (ends_at is null or ends_at > now())),
    'source', (select e.source from public.entitlements e where e.user_id = p_user order by e.created_at desc limit 1),
    'billing', 'not_connected'
  )
$$;

create or replace function public.get_my_pro() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  prog jsonb := public.pro_sync_milestones(v);
  sch public.pro_scheduler;
begin
  select * into sch from public.pro_scheduler where id;
  return jsonb_build_object(
    'version', public.pro_universe_version(),
    'membership', public.pro_membership(v),
    'milestones', coalesce((select jsonb_object_agg(key, earned_at) from public.pro_milestones where user_id = v), '{}'::jsonb),
    'progress', prog,
    'equips', coalesce((select jsonb_object_agg(e.slot, jsonb_build_object('item', e.item_id, 'active', public.pro_owns(v, e.item_id)))
                        from public.pro_equips e where e.user_id = v), '{}'::jsonb),
    'wishlist', coalesce((select jsonb_agg(item_id order by added_at desc) from public.pro_wishlist where user_id = v), '[]'::jsonb),
    'settings', coalesce((select data from public.pro_settings where user_id = v), '{}'::jsonb),
    'scheduler', jsonb_build_object('running', sch.last_run is not null and sch.last_run > now() - interval '15 minutes',
                                    'last_run', sch.last_run),
    'limits', jsonb_build_object('drafts', case when public.is_pro(v) then 200 else 20 end,
                                 'scheduled', case when public.is_pro(v) then 50 else 3 end)
  );
end $$;

