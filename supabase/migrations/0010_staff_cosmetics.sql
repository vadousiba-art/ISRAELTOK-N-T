-- ============================================================================
-- YORU — staff cosmetics. docs/pro-universe.md ("Staff cosmetics")
--
-- Two reserved sets that mark the people who run YORU:
--   * Founder's Throne  unlock 'staff:owner'  (the founder only)
--   * Night Watch       unlock 'staff:admin'  (admins and the founder)
-- Ownership is decided here from profiles.role, so nobody can equip them by
-- crafting a request, complimentary Pro doesn't include them, and they fall
-- back to the default by themselves if the role is removed (the stored
-- choice is kept). They are never sold and never earned.
--
-- Additive: widens one check constraint, adds 16 catalog rows, redefines
-- three functions with the same signatures. Safe to run more than once.
-- ============================================================================

alter table public.pro_catalog drop constraint if exists pro_catalog_unlock_check;
alter table public.pro_catalog add constraint pro_catalog_unlock_check
  check (unlock in ('free','pro','staff:admin','staff:owner') or unlock ~ '^milestone:[a-z_]+$');

