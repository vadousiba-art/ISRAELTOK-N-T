create or replace function public.pro_staff_allows(p_user uuid, p_unlock text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles p
    where p.id = p_user and not p.banned
      and (p.role = 'owner' or (p_unlock = 'staff:admin' and p.role = 'admin'))
  )
$$;

create or replace function public.pro_owns(p_user uuid, p_item text) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((
    select case
      when c.status = 'retired' then false
      when c.unlock = 'free' then true
      when c.unlock = 'pro' then public.is_pro(p_user)
      -- Staff items: decided by the account's role, never by Pro or testing.
      when c.unlock like 'staff:%' then public.pro_staff_allows(p_user, c.unlock)
      -- Testers (members given complimentary Pro by an admin) can use every
      -- cosmetic, including ones normally unlocked by a milestone. The
      -- milestones themselves stay earned-only: they claim an achievement.
      when c.cat <> 'milestone' and public.pro_is_tester(p_user) then true
      else exists (select 1 from public.pro_milestones m where m.user_id = p_user and m.key = substr(c.unlock, 11))
    end
    from public.pro_catalog c where c.id = p_item
  ), false)
$$;

create or replace function public.pro_check_equip(v uuid, p_slot text, p_item text) returns void
language plpgsql stable security definer set search_path = public as $$
declare
  c public.pro_catalog;
begin
  if public.pro_slot_cat(p_slot) is null then raise exception 'INVALID|Unknown slot.'; end if;
  select * into c from public.pro_catalog where id = p_item;
  if c.id is null or c.status = 'retired' then raise exception 'NOT_FOUND|No such item.' using errcode = 'P0002'; end if;
  if c.cat <> public.pro_slot_cat(p_slot) then raise exception 'INVALID|That item doesn''t go in that slot.'; end if;
  if not public.pro_owns(v, p_item) then
    if c.unlock like 'staff:%' then raise exception 'FORBIDDEN|That item is reserved for YORU staff.' using errcode = '42501'; end if;
    if c.unlock = 'pro' then raise exception 'FORBIDDEN|That item is part of YORU Pro.' using errcode = '42501'; end if;
    raise exception 'FORBIDDEN|Earn this one first.' using errcode = '42501';
  end if;
  if c.status = 'experimental' and not coalesce((select data -> 'labs' ? 'lab.experimental_effects' from public.pro_settings where user_id = v), false) then
    raise exception 'FORBIDDEN|Turn on Experimental Effects in the Preview Lab first.' using errcode = '42501';
  end if;
end $$;

-- get_my_pro also reports the caller's role, so the app can show staff items
-- to staff (the server still decides ownership).
create or replace function public.get_my_pro() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v uuid := public.require_member();
  prog jsonb := public.pro_sync_milestones(v);
  sch public.pro_scheduler;
begin
  select * into sch from public.pro_scheduler where id;
  return jsonb_build_object(
    'version', public.pro_universe_version(),
    'role', (select role from public.profiles where id = v),
    'membership', public.pro_membership(v),
    'milestones', coalesce((select jsonb_object_agg(key, earned_at) from public.pro_milestones where user_id = v), '{}'::jsonb),
    'progress', prog,
    'equips', coalesce((select jsonb_object_agg(e.slot, jsonb_build_object('item', e.item_id, 'active', public.pro_owns(v, e.item_id)))
                        from public.pro_equips e where e.user_id = v), '{}'::jsonb),
    'wishlist', coalesce((select jsonb_agg(item_id order by added_at desc) from public.pro_wishlist where user_id = v), '[]'::jsonb),
    'settings', coalesce((select data from public.pro_settings where user_id = v), '{}'::jsonb),
    'scheduler', jsonb_build_object('running', sch.last_run is not null and sch.last_run > now() - interval '15 minutes',
                                    'last_run', sch.last_run),
    'limits', jsonb_build_object('drafts', case when public.is_pro(v) then 200 else 20 end,
                                 'scheduled', case when public.is_pro(v) then 50 else 3 end)
  );
end $$;

